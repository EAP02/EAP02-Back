    PRIMARY KEY (usuario_id, publicacion_id),

    CONSTRAINT ck_reaccion_pub_tipo CHECK (tipo IN ('ME_GUSTA','UTIL','INNOVADOR'))
);

COMMENT ON TABLE reaccion_publicacion IS
    'La clave primaria compuesta impone una sola reaccion por usuario y publicacion. Cambiar de tipo es UPDATE, no una segunda fila.';


CREATE TABLE reaccion_comentario (
    usuario_id    uuid        NOT NULL REFERENCES usuario(id)    ON DELETE CASCADE,
    comentario_id uuid        NOT NULL REFERENCES comentario(id) ON DELETE CASCADE,
