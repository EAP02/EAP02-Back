--  DevNet - Red Social para Desarrolladores
--  V1__baseline.sql : modelo fisico inicial (Sprint 1)
--
--  Motor    : PostgreSQL 15 o superior (Supabase)
--  Gestion  : Flyway. Esta carpeta es la UNICA fuente de verdad del esquema.
--             Hibernate corre siempre con ddl-auto=validate (ADR-003).
--  Modelo   : docs/bd/02-modelo-logico.md
--  Consultas: docs/bd/01-consultas-clave.md
--
--  CONVENCIONES
--    * snake_case, identificadores en espanol y sin acentos.
--    * Claves primarias uuid generadas por la base con gen_random_uuid()
--      (nucleo de PostgreSQL desde la version 13; no requiere extension).
--    * Toda marca de tiempo es timestamptz almacenada en UTC.
--    * Los estados se modelan como text + CHECK y no como ENUM nativo,
--      por compatibilidad con @Enumerated(EnumType.STRING) de JPA.
--    * Sin ON DELETE CASCADE sobre contenido con valor historico: se usa
--      desactivacion de cuenta y borrado logico para preservar trazabilidad.
--      CASCADE se reserva a dependencias estructurales puras.
--
--  FUERA DE ALCANCE DE ESTA MIGRACION
--    Roles de base de datos y privilegios -> docs/bd/db-roles.sql
--      (aprovisionamiento del entorno, se ejecuta una vez por proyecto).
--    Triggers de auditoria y de contadores  -> V3 (Sprint 3).
--    sp_consolidar_metricas_diarias          -> V3 (Sprint 3).
