-- P01 feed: indice PARCIAL, el feed solo mira publicaciones en estado PUBLICADO
CREATE INDEX ix_publicacion_feed
    ON publicacion (publicado_en DESC, id DESC)
    WHERE estado = 'PUBLICADO';

-- P04 busqueda por texto completo
CREATE INDEX ix_publicacion_busqueda
    ON publicacion USING GIN (busqueda_tsv);

-- P01, P10 publicaciones por autor y estado
CREATE INDEX ix_publicacion_autor_estado
    ON publicacion (autor_id, estado, creado_en DESC);

-- P01, P03 resolucion de etiquetas en sentido tecnologia -> publicacion
CREATE INDEX ix_publicacion_tecnologia_inverso
    ON publicacion_tecnologia (tecnologia_id, publicacion_id);

-- P03 proyectos que buscan colaboradores
CREATE INDEX ix_proyecto_busca_colaboradores
    ON publicacion_proyecto (publicacion_id)
    WHERE busca_colaboradores = true;

-- P02 hilo de comentarios: ancla del CTE recursivo
CREATE INDEX ix_comentario_publicacion_padre
    ON comentario (publicacion_id, comentario_padre_id, creado_en);

-- P05 bandeja: ultimo mensaje por conversacion y conteo de no leidos
CREATE INDEX ix_mensaje_conversacion
    ON mensaje (conversacion_id, enviado_en DESC);

-- P05 conversaciones de un usuario
CREATE INDEX ix_participante_usuario
    ON participante_conversacion (usuario_id, conversacion_id)
    WHERE abandonada_en IS NULL;

-- P05 unicidad de la conversacion directa entre dos usuarios
CREATE UNIQUE INDEX ux_conversacion_directa
    ON conversacion (clave_directa)
    WHERE clave_directa IS NOT NULL;

-- P06 libro mayor de reputacion por usuario
CREATE INDEX ix_evento_reputacion_usuario
    ON evento_reputacion (usuario_id, creado_en DESC);

-- P07 seguidores (el sentido inverso ya lo cubre la clave primaria compuesta)
CREATE INDEX ix_seguimiento_seguido
    ON seguimiento (seguido_id, seguidor_id);

-- P08 solicitudes de colaboracion de un usuario
CREATE INDEX ix_colaboracion_usuario
    ON colaboracion (usuario_id, estado);

-- P09 cola de moderacion: parcial, solo lo que esta pendiente
CREATE INDEX ix_reporte_pendiente
    ON reporte_moderacion (creado_en)
    WHERE estado IN ('ABIERTO','EN_REVISION');

-- P11 historial de una publicacion
CREATE INDEX ix_historial_publicacion
    ON historial_estado_publicacion (publicacion_id, creado_en DESC);

-- P12 suspensiones vigentes
CREATE INDEX ix_suspension_vigente
    ON suspension (usuario_id, termina_en DESC)
    WHERE levantada_en IS NULL;

-- P16 busqueda en auditoria
CREATE INDEX ix_auditoria_registro ON auditoria (tabla, registro_id, creado_en DESC);
CREATE INDEX ix_auditoria_trace    ON auditoria (trace_id) WHERE trace_id IS NOT NULL;

-- P17 catalogo pendiente de aprobacion
CREATE INDEX ix_tecnologia_pendiente
    ON tecnologia (creado_en)
    WHERE aprobada = false;

-- Identidad: limpieza y revocacion de tokens
CREATE INDEX ix_token_familia
    ON token_refresco (familia)
    WHERE revocado_en IS NULL;
CREATE INDEX ix_token_usuario_vigente
    ON token_refresco (usuario_id, expira_en)
    WHERE revocado_en IS NULL AND consumido_en IS NULL;


