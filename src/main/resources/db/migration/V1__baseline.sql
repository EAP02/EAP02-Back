CREATE TABLE comentario (
    id                  uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    publicacion_id      uuid        NOT NULL REFERENCES publicacion(id) ON DELETE CASCADE,
    autor_id            uuid        NOT NULL REFERENCES usuario(id),
    comentario_padre_id uuid        REFERENCES comentario(id) ON DELETE CASCADE,
    contenido           text        NOT NULL,
    estado              text        NOT NULL DEFAULT 'PUBLICADO',
    profundidad         smallint    NOT NULL DEFAULT 0,
    contador_reacciones integer     NOT NULL DEFAULT 0,
    editado             boolean     NOT NULL DEFAULT false,
    creado_en           timestamptz NOT NULL DEFAULT now(),
    actualizado_en      timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT ck_comentario_estado      CHECK (estado IN ('PUBLICADO','OCULTO','ELIMINADO')),
    CONSTRAINT ck_comentario_contenido   CHECK (length(btrim(contenido)) BETWEEN 1 AND 5000),
    CONSTRAINT ck_comentario_profundidad CHECK (profundidad BETWEEN 0 AND 5),
    CONSTRAINT ck_comentario_raiz
        CHECK ((comentario_padre_id IS NULL AND profundidad = 0)
            OR (comentario_padre_id IS NOT NULL AND profundidad > 0))
);

COMMENT ON CONSTRAINT ck_comentario_profundidad ON comentario IS
    'La cota no es estetica: sin ella el CTE recursivo del hilo (P02) no tiene techo de costo.';


ALTER TABLE publicacion_discusion
    ADD CONSTRAINT fk_discusion_comentario_aceptado
    FOREIGN KEY (comentario_aceptado_id) REFERENCES comentario(id) ON DELETE SET NULL;


CREATE TABLE reaccion_publicacion (
