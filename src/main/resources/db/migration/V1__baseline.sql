CREATE TABLE rol (
    id          smallint     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo      text         NOT NULL UNIQUE,
    descripcion text         NOT NULL,
    exige_mfa   boolean      NOT NULL DEFAULT false,
    CONSTRAINT ck_rol_codigo
        CHECK (codigo IN ('VISITANTE', 'DESARROLLADOR', 'MODERADOR', 'ADMIN'))
);

COMMENT ON COLUMN rol.exige_mfa IS
    'Convierte "este rol exige segundo factor" en dato y no en condicional del codigo (ADR-004).';


CREATE TABLE permiso (
    id          smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo      text     NOT NULL UNIQUE,
    descripcion text     NOT NULL
);

COMMENT ON TABLE permiso IS
    'La autorizacion evalua permisos, no nombres de rol: cambiar lo que puede hacer un rol es una fila, no un despliegue.';


CREATE TABLE rol_permiso (
    rol_id     smallint NOT NULL REFERENCES rol(id)     ON DELETE CASCADE,
    permiso_id smallint NOT NULL REFERENCES permiso(id) ON DELETE CASCADE,
    PRIMARY KEY (rol_id, permiso_id)
);


CREATE TABLE usuario (
    id               uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    correo           text        NOT NULL,
    nombre_usuario   text        NOT NULL,
    clave_hash       text,
    estado           text        NOT NULL DEFAULT 'ACTIVO',
    mfa_habilitado   boolean     NOT NULL DEFAULT false,
    mfa_secreto      text,
    intentos_fallidos smallint   NOT NULL DEFAULT 0,
    bloqueado_hasta  timestamptz,
    ultimo_acceso_en timestamptz,
    creado_en        timestamptz NOT NULL DEFAULT now(),
    actualizado_en   timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT ck_usuario_estado
        CHECK (estado IN ('ACTIVO', 'SUSPENDIDO', 'DESACTIVADO')),
    CONSTRAINT ck_usuario_correo_formato
        CHECK (correo ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    CONSTRAINT ck_usuario_nombre_usuario_formato
        CHECK (nombre_usuario ~ '^[a-z0-9][a-z0-9_-]{2,29}$'),
    CONSTRAINT ck_usuario_intentos
        CHECK (intentos_fallidos >= 0)
);

CREATE UNIQUE INDEX ux_usuario_correo         ON usuario (lower(correo));
CREATE UNIQUE INDEX ux_usuario_nombre_usuario ON usuario (lower(nombre_usuario));

COMMENT ON COLUMN usuario.clave_hash IS
    'Argon2id. Nulo cuando la cuenta se creo por GitHub y aun no fijo contrasena (ADR-004).';
COMMENT ON COLUMN usuario.mfa_secreto IS
    'Secreto TOTP cifrado a nivel de columna. La clave vive en variable de entorno, nunca en el repositorio.';
COMMENT ON COLUMN usuario.estado IS
    'No existe PENDIENTE_VERIFICACION: la verificacion se resuelve vinculando GitHub (ADR-004).';


CREATE TABLE usuario_rol (
    usuario_id   uuid        NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
    rol_id       smallint    NOT NULL REFERENCES rol(id),
    asignado_por uuid        REFERENCES usuario(id),
    asignado_en  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (usuario_id, rol_id)
);


CREATE TABLE identidad_externa (
    id              uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    usuario_id      uuid        NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
    proveedor       text        NOT NULL,
    sujeto_externo  text        NOT NULL,
    usuario_externo text        NOT NULL,
    url_perfil      text,
    vinculado_en    timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT ck_identidad_proveedor CHECK (proveedor IN ('GITHUB')),
    CONSTRAINT ux_identidad_proveedor_sujeto UNIQUE (proveedor, sujeto_externo),
    CONSTRAINT ux_identidad_usuario_proveedor UNIQUE (usuario_id, proveedor)
);

COMMENT ON TABLE identidad_externa IS
    'Tener una fila aqui es lo que marca el perfil como verificado, requisito para publicar (regla R1).';


CREATE TABLE token_refresco (
    id             uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    usuario_id     uuid        NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
    token_hash     text        NOT NULL UNIQUE,
    familia        uuid        NOT NULL,
    emitido_en     timestamptz NOT NULL DEFAULT now(),
    expira_en      timestamptz NOT NULL,
    consumido_en   timestamptz,
    revocado_en    timestamptz,
    reemplazado_por uuid       REFERENCES token_refresco(id),
    ip_origen      inet,
    agente_usuario text,

    CONSTRAINT ck_token_vigencia CHECK (expira_en > emitido_en)
);

COMMENT ON COLUMN token_refresco.token_hash IS
    'Solo el hash. El token en claro nunca se almacena ni se registra en logs (lineamientos 6.2).';
COMMENT ON COLUMN token_refresco.familia IS
    'Rotacion con deteccion de reuso: si llega un token ya consumido se revoca la familia completa (ADR-004).';


CREATE TABLE suspension (
    id           uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    usuario_id   uuid        NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
    motivo       text        NOT NULL,
    inicia_en    timestamptz NOT NULL DEFAULT now(),
    termina_en   timestamptz NOT NULL,
    aplicada_por uuid        REFERENCES usuario(id),
    automatica   boolean     NOT NULL DEFAULT false,
    levantada_en timestamptz,

    CONSTRAINT ck_suspension_rango CHECK (termina_en > inicia_en),
    CONSTRAINT ck_suspension_autoria
        CHECK ((automatica AND aplicada_por IS NULL)
            OR (NOT automatica AND aplicada_por IS NOT NULL))
);

COMMENT ON CONSTRAINT ck_suspension_autoria ON suspension IS
    'Una sancion automatica (regla R6) no tiene actor; una manual siempre lo tiene. Evita un usuario "sistema" ficticio.';


