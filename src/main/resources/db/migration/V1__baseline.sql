CREATE TABLE reporte_moderacion (
    id             uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    reportante_id  uuid        NOT NULL REFERENCES usuario(id),
    publicacion_id uuid        REFERENCES publicacion(id) ON DELETE CASCADE,
    comentario_id  uuid        REFERENCES comentario(id)  ON DELETE CASCADE,
    motivo         text        NOT NULL,
    detalle        text,
    estado         text        NOT NULL DEFAULT 'ABIERTO',
    moderador_id   uuid        REFERENCES usuario(id),
    resolucion     text,
    es_apelacion   boolean     NOT NULL DEFAULT false,
    creado_en      timestamptz NOT NULL DEFAULT now(),
    resuelto_en    timestamptz,

    CONSTRAINT ck_reporte_objetivo_exclusivo
        CHECK ((publicacion_id IS NULL) <> (comentario_id IS NULL)),
    CONSTRAINT ck_reporte_motivo
        CHECK (motivo IN ('SPAM','ACOSO','CONTENIDO_INAPROPIADO','PLAGIO','OTRA')),
    CONSTRAINT ck_reporte_estado
        CHECK (estado IN ('ABIERTO','EN_REVISION','RESUELTO_ACEPTADO','RESUELTO_DESESTIMADO')),
    CONSTRAINT ck_reporte_no_autorreporte
        CHECK (reportante_id <> coalesce(moderador_id, '00000000-0000-0000-0000-000000000000'::uuid)),
    CONSTRAINT ck_reporte_resolucion_coherente
        CHECK ((estado LIKE 'RESUELTO%'
                    AND moderador_id IS NOT NULL
                    AND resolucion IS NOT NULL
                    AND length(btrim(resolucion)) >= 20
                    AND resuelto_en IS NOT NULL)
            OR (estado NOT LIKE 'RESUELTO%'))
);

COMMENT ON CONSTRAINT ck_reporte_objetivo_exclusivo ON reporte_moderacion IS
    'Disyuncion exclusiva sin renunciar a claves foraneas reales: exactamente una publicacion o un comentario, nunca ambos ni ninguno.';
COMMENT ON CONSTRAINT ck_reporte_no_autorreporte ON reporte_moderacion IS
    'Regla R3, parte declarativa: el moderador que resuelve no puede ser el reportante. Que tampoco sea el autor se valida en el dominio, porque la autoria vive en otra tabla.';
COMMENT ON CONSTRAINT ck_reporte_resolucion_coherente ON reporte_moderacion IS
    'Regla R3: no hay resolucion silenciosa. Motivo escrito de 20 caracteres minimo, moderador y fecha.';


