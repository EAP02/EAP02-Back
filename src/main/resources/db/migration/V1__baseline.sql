    creado_en       timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT ck_evento_reputacion_tipo CHECK (tipo_evento IN (
        'REACCION_EN_PUBLICACION',
        'REACCION_EN_COMENTARIO',
        'COMENTARIO_ACEPTADO',
        'PROYECTO_CON_REPOSITORIO',
