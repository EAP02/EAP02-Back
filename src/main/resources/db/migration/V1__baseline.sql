CREATE TABLE conversacion (
    id                uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    creada_por        uuid        NOT NULL REFERENCES usuario(id),
    clave_directa     text,
    ultimo_mensaje_en timestamptz,
    creada_en         timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT ck_conversacion_clave_directa
        CHECK (clave_directa IS NULL OR clave_directa ~ '^[0-9a-f-]{36}:[0-9a-f-]{36}$')
);

COMMENT ON COLUMN conversacion.clave_directa IS
    'Los dos uuid de los participantes ordenados como "menor:mayor". Con el indice unico parcial impide conversaciones directas duplicadas, sin renunciar a soportar grupos despues (donde queda nula).';


CREATE TABLE participante_conversacion (
    conversacion_id uuid        NOT NULL REFERENCES conversacion(id) ON DELETE CASCADE,
    usuario_id      uuid        NOT NULL REFERENCES usuario(id)      ON DELETE CASCADE,
    ultimo_leido_en timestamptz,
    silenciada      boolean     NOT NULL DEFAULT false,
    abandonada_en   timestamptz,
    unido_en        timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (conversacion_id, usuario_id)
);

COMMENT ON COLUMN participante_conversacion.ultimo_leido_en IS
    'Evita una tabla de estado de lectura por mensaje y por participante, que multiplicaria el volumen de la tabla que mas crece para responder la misma pregunta (P05).';


CREATE TABLE mensaje (
    id              uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    conversacion_id uuid        NOT NULL REFERENCES conversacion(id) ON DELETE CASCADE,
    remitente_id    uuid        NOT NULL REFERENCES usuario(id),
    contenido       text        NOT NULL,
    enviado_en      timestamptz NOT NULL DEFAULT now(),
    editado_en      timestamptz,
    eliminado_en    timestamptz,

    CONSTRAINT ck_mensaje_contenido CHECK (length(btrim(contenido)) BETWEEN 1 AND 4000)
);

COMMENT ON COLUMN mensaje.eliminado_en IS
    'Borrado logico: el fisico romperia la continuidad de la conversacion y eliminaria evidencia necesaria para moderar acoso.';


