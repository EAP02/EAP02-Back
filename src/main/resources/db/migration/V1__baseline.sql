-- ----------------------------------------------------------------------------
-- 0. Funcion comun de marca de actualizacion
-- ----------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION fn_set_actualizado_en()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.actualizado_en := now();
    RETURN NEW;
END;
$$;

COMMENT ON FUNCTION fn_set_actualizado_en() IS
    'Mantiene actualizado_en. Es mantenimiento de metadatos, no logica de negocio (lineamientos 5.4).';


