    'Relacion reflexiva no simetrica sobre usuario. Seguir no implica ser seguido.';


-- ============================================================================
-- 3. CONTENIDO: supertipo publicacion con especializacion proyecto / discusion
-- ============================================================================

CREATE TABLE publicacion (
    id                    uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    autor_id              uuid        NOT NULL REFERENCES usuario(id),
    tipo                  text        NOT NULL,
    titulo                text        NOT NULL,
    contenido             text        NOT NULL,
    estado                text        NOT NULL DEFAULT 'BORRADOR',
    contador_comentarios  integer     NOT NULL DEFAULT 0,
    contador_reacciones   integer     NOT NULL DEFAULT 0,
    version               integer     NOT NULL DEFAULT 0,
    publicado_en          timestamptz,
    creado_en             timestamptz NOT NULL DEFAULT now(),
    actualizado_en        timestamptz NOT NULL DEFAULT now(),

    -- El cast explicito a regconfig fija la resolucion a to_tsvector(regconfig, text),
    -- que es IMMUTABLE y por tanto admisible en una columna generada.
    busqueda_tsv tsvector GENERATED ALWAYS AS (
        to_tsvector('spanish'::regconfig, coalesce(titulo, '') || ' ' || coalesce(contenido, ''))
    ) STORED,

    CONSTRAINT ck_publicacion_tipo   CHECK (tipo IN ('PROYECTO','DISCUSION')),
    CONSTRAINT ck_publicacion_estado
        CHECK (estado IN ('BORRADOR','PUBLICADO','EN_REVISION','OCULTO','ARCHIVADO')),
    CONSTRAINT ck_publicacion_titulo  CHECK (length(btrim(titulo)) BETWEEN 5 AND 200),
    CONSTRAINT ck_publicacion_contenido CHECK (length(btrim(contenido)) >= 20),
    CONSTRAINT ck_publicacion_contadores
        CHECK (contador_comentarios >= 0 AND contador_reacciones >= 0),
    CONSTRAINT ck_publicacion_publicado_en
        CHECK ((estado = 'BORRADOR' AND publicado_en IS NULL)
            OR (estado <> 'BORRADOR' AND publicado_en IS NOT NULL))
);

COMMENT ON TABLE publicacion IS
    'Supertipo de PROYECTO y DISCUSION. Permite que comentario, reaccion y reporte usen una clave foranea real en lugar de una referencia polimorfica.';
COMMENT ON COLUMN publicacion.busqueda_tsv IS
    'Columna generada y persistida: el vector no se calcula en tiempo de consulta. Indice GIN mas abajo.';
COMMENT ON COLUMN publicacion.version IS
    'Bloqueo optimista de JPA. Produce el 409 CONFLICTO_CONCURRENCIA del ADR-005.';
COMMENT ON CONSTRAINT ck_publicacion_publicado_en ON publicacion IS
    'Un borrador nunca tiene fecha de publicacion; cualquier otro estado siempre la tiene.';


CREATE TABLE publicacion_proyecto (
    publicacion_id       uuid     PRIMARY KEY REFERENCES publicacion(id) ON DELETE CASCADE,
    resumen              text     NOT NULL,
    licencia             text,
    estado_proyecto      text     NOT NULL DEFAULT 'IDEA',
    busca_colaboradores  boolean  NOT NULL DEFAULT false,
    max_colaboradores    smallint NOT NULL DEFAULT 5,
    url_demo             text,

    CONSTRAINT ck_proyecto_estado
        CHECK (estado_proyecto IN ('IDEA','EN_DESARROLLO','ESTABLE','PAUSADO')),
    CONSTRAINT ck_proyecto_max_colaboradores
        CHECK (max_colaboradores BETWEEN 1 AND 50)
);


CREATE TABLE publicacion_discusion (
    publicacion_id        uuid    PRIMARY KEY REFERENCES publicacion(id) ON DELETE CASCADE,
    categoria             text    NOT NULL,
    resuelta              boolean NOT NULL DEFAULT false,
    comentario_aceptado_id uuid,   -- FK anadida mas abajo: dependencia circular con comentario

    CONSTRAINT ck_discusion_categoria
        CHECK (categoria IN ('PREGUNTA','DEBATE','ANUNCIO','RECURSO')),
    CONSTRAINT ck_discusion_resuelta_coherente
        CHECK ((resuelta AND comentario_aceptado_id IS NOT NULL)
            OR (NOT resuelta AND comentario_aceptado_id IS NULL))
);


CREATE TABLE repositorio (
    id                      uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    publicacion_proyecto_id uuid        NOT NULL REFERENCES publicacion_proyecto(publicacion_id) ON DELETE CASCADE,
    proveedor               text        NOT NULL DEFAULT 'GITHUB',
    url                     text        NOT NULL UNIQUE,
    rama_principal          text        NOT NULL DEFAULT 'main',
    estrellas               integer     NOT NULL DEFAULT 0,
    ultima_sincronizacion   timestamptz,

    CONSTRAINT ck_repositorio_proveedor CHECK (proveedor IN ('GITHUB','GITLAB','OTRO')),
    CONSTRAINT ck_repositorio_url       CHECK (url ~* '^https://'),
    CONSTRAINT ck_repositorio_estrellas  CHECK (estrellas >= 0)
);


CREATE TABLE publicacion_tecnologia (
    publicacion_id uuid     NOT NULL REFERENCES publicacion(id) ON DELETE CASCADE,
    tecnologia_id  smallint NOT NULL REFERENCES tecnologia(id),
    PRIMARY KEY (publicacion_id, tecnologia_id)
);

COMMENT ON TABLE publicacion_tecnologia IS
    'Regla R1: entre 1 y 5 tecnologias por publicacion. La cota superior se valida en el dominio porque una restriccion declarativa no puede contar filas de otra tabla.';


CREATE TABLE historial_estado_publicacion (
    id              uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    publicacion_id  uuid        NOT NULL REFERENCES publicacion(id) ON DELETE CASCADE,
    estado_anterior text,
    estado_nuevo    text        NOT NULL,
    actor_id        uuid        REFERENCES usuario(id),
    motivo          text,
    creado_en       timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT ck_historial_estados_distintos
        CHECK (estado_anterior IS NULL OR estado_anterior <> estado_nuevo)
);

COMMENT ON TABLE historial_estado_publicacion IS
    'Regla R7: toda transicion escribe aqui en la misma transaccion que el cambio de estado. Si no se puede escribir el historial, la transicion no ocurre.';


CREATE TABLE colaboracion (
    id                      uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    publicacion_proyecto_id uuid        NOT NULL REFERENCES publicacion_proyecto(publicacion_id) ON DELETE CASCADE,
    usuario_id              uuid        NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
    estado                  text        NOT NULL DEFAULT 'SOLICITADA',
    rol_colaborador         text,
    mensaje_solicitud       text,
    resuelto_por            uuid        REFERENCES usuario(id),
    solicitado_en           timestamptz NOT NULL DEFAULT now(),
    resuelto_en             timestamptz,
    retirado_en             timestamptz,

    CONSTRAINT ck_colaboracion_estado
        CHECK (estado IN ('SOLICITADA','ACEPTADA','RECHAZADA','ACTIVA','RETIRADA')),
    CONSTRAINT ux_colaboracion_proyecto_usuario
        UNIQUE (publicacion_proyecto_id, usuario_id)
);

COMMENT ON CONSTRAINT ux_colaboracion_proyecto_usuario ON colaboracion IS
    'El reingreso tras retiro transiciona la fila existente, no crea una nueva. Es lo que sostiene la regla C3.';


